#!/usr/bin/env node
'use strict';
// Turns a results JSONL from run.js into RESULTS.md, an SVG chart and a compact README table.
//   node benchmarks/token-cost/report.js <results.jsonl> [--md <file>] [--svg <file>]
const fs = require('fs');
const path = require('path');

const HERE = __dirname;
const REPO = path.resolve(HERE, '..', '..');

function parseArgs(argv) {
  const o = { input: null, md: path.join(HERE, 'RESULTS.md'), svg: path.join(REPO, 'docs', 'assets', 'token-cost.svg') };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--md') o.md = argv[++i];
    else if (argv[i] === '--svg') o.svg = argv[++i];
    else if (!o.input) o.input = argv[i];
    else throw new Error('unexpected argument: ' + argv[i]);
  }
  if (!o.input) throw new Error('usage: node benchmarks/token-cost/report.js <results.jsonl> [--md <file>] [--svg <file>]');
  return o;
}

function readRuns(file) {
  return fs.readFileSync(file, 'utf8').split(/\r?\n/).filter((l) => l.trim()).map((l) => JSON.parse(l));
}

function median(a) {
  if (!a.length) return null;
  const s = a.slice().sort((x, y) => x - y);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}
const sum = (a) => a.reduce((x, y) => x + y, 0);

function cell(runs) {
  return {
    n: runs.length,
    solved: runs.filter((r) => r.success).length,
    medCost: median(runs.map((r) => r.cost_usd)),
    medTokens: median(runs.map((r) => r.total_tokens)),
    medTurns: median(runs.map((r) => r.turns)),
    totalCost: sum(runs.map((r) => r.cost_usd)),
    totalTokens: sum(runs.map((r) => r.total_tokens)),
    totalTurns: sum(runs.map((r) => r.turns)),
    injectedRuns: runs.filter((r) => r.injected > 0).length,
  };
}

function summarize(runs) {
  const tasks = Array.from(new Set(runs.map((r) => r.task))).sort();
  const per = tasks.map((t) => ({
    task: t,
    off: cell(runs.filter((r) => r.task === t && r.condition === 'off')),
    on: cell(runs.filter((r) => r.task === t && r.condition === 'on')),
  }));
  return {
    tasks: per,
    off: cell(runs.filter((r) => r.condition === 'off')),
    on: cell(runs.filter((r) => r.condition === 'on')),
    models: Array.from(new Set(runs.map((r) => r.model))),
  };
}

const usd = (v) => (v == null ? 'n/a' : '$' + (v >= 1 ? v.toFixed(2) : v.toFixed(4)));
const int = (v) => (v == null ? 'n/a' : Math.round(v).toLocaleString('en-US'));
const turns = (v) => (v == null ? 'n/a' : String(Math.round(v * 10) / 10));
function delta(off, on) {
  if (off == null || on == null || off === 0) return 'n/a';
  const d = ((on - off) / off) * 100;
  return (d > 0 ? '+' : '') + d.toFixed(1) + '%';
}
const frac = (c) => (c.n ? c.solved + '/' + c.n : 'n/a');
const perSolved = (c) => (c.solved ? c.totalCost / c.solved : null);

function renderMarkdown(s, inputName) {
  const L = [];
  L.push('# Token cost benchmark: results');
  L.push('');
  L.push('Generated by `benchmarks/token-cost/report.js` from `' + inputName + '`. Model: ' + s.models.join(', ') + '. Runs: ' +
    (s.off.n + s.on.n) + ' (' + s.off.n + ' off, ' + s.on.n + ' on).');
  L.push('');
  L.push('## Method');
  L.push('');
  L.push('An agent works on a small synthetic project that contains one non-obvious gotcha. A "previous session" already solved that gotcha and left a lesson. ' +
    'Each task runs headless (`claude -p`) in two conditions:');
  L.push('');
  L.push('- **off**: the hooks are installed but disabled (`MLP_DISABLE=1`).');
  L.push('- **on**: the hooks are enabled. The lessons store holds the lesson of every task plus the six generic example lessons, so the matcher has to pick the right one.');
  L.push('');
  L.push('A run counts as solved only if the task\'s `verify.js` exits 0 afterwards. Cost, tokens and turns come from the Claude Code JSON result. ' +
    'Tokens are input + output + cache read + cache creation. One task is a control with no relevant lesson, to show the overhead when nothing matches.');
  L.push('');
  L.push('## Per task');
  L.push('');
  L.push('| Task | Solved off | Solved on | Median cost off | Median cost on | Δ cost | Median tokens off | Median tokens on | Median turns off | Median turns on | Runs with injection (on) |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const t of s.tasks) {
    L.push('| ' + [t.task, frac(t.off), frac(t.on), usd(t.off.medCost), usd(t.on.medCost), delta(t.off.medCost, t.on.medCost),
      int(t.off.medTokens), int(t.on.medTokens), turns(t.off.medTurns), turns(t.on.medTurns),
      t.on.n ? t.on.injectedRuns + '/' + t.on.n : 'n/a'].join(' | ') + ' |');
  }
  L.push('| **All runs** | ' + [frac(s.off), frac(s.on), usd(s.off.medCost), usd(s.on.medCost), delta(s.off.medCost, s.on.medCost),
    int(s.off.medTokens), int(s.on.medTokens), turns(s.off.medTurns), turns(s.on.medTurns),
    s.on.n ? s.on.injectedRuns + '/' + s.on.n : 'n/a'].join(' | ') + ' |');
  L.push('');
  L.push('## Totals');
  L.push('');
  L.push('| | off | on | Δ |');
  L.push('|---|---|---|---|');
  L.push('| Total cost | ' + usd(s.off.totalCost) + ' | ' + usd(s.on.totalCost) + ' | ' + delta(s.off.totalCost, s.on.totalCost) + ' |');
  L.push('| Total tokens | ' + int(s.off.totalTokens) + ' | ' + int(s.on.totalTokens) + ' | ' + delta(s.off.totalTokens, s.on.totalTokens) + ' |');
  L.push('| Total turns | ' + int(s.off.totalTurns) + ' | ' + int(s.on.totalTurns) + ' | ' + delta(s.off.totalTurns, s.on.totalTurns) + ' |');
  L.push('| Solved runs | ' + frac(s.off) + ' | ' + frac(s.on) + ' | |');
  L.push('| **Cost per solved task** | ' + usd(perSolved(s.off)) + ' | ' + usd(perSolved(s.on)) + ' | ' + delta(perSolved(s.off), perSolved(s.on)) + ' |');
  L.push('');
  L.push('Cost per solved task is total cost of all runs in the condition divided by the number of solved runs, so failed runs count against a condition.');
  L.push('');
  L.push('![Median cost per task, lessons off vs on](../../docs/assets/token-cost.svg)');
  L.push('');
  L.push('## Limitations');
  L.push('');
  L.push('- **Synthetic tasks.** Five tiny projects written for this benchmark, each with a gotcha chosen so that a lesson helps. Real projects are larger and noisier.');
  L.push('- **One model.** Results for ' + s.models.join(', ') + ' say nothing certain about other models.');
  L.push('- **Small n.** A handful of repetitions per cell. Medians over a few runs move a lot; treat differences of a few percent as noise.');
  L.push('- **Lessons written in advance.** The lessons were written by hand with the solution known, and their keywords were chosen to match the task phrasing. In real use a lesson comes from an earlier failed session and may match worse (or be wrong).');
  L.push('- **Delivery is guaranteed, use is not.** The hooks deliver a matching lesson deterministically, but the benchmark cannot force the model to follow it. A run counted as "injected" only means the text reached the context.');
  L.push('- **Overhead is included.** In the "on" condition the injected text adds input tokens; the control task shows that cost when nothing matches.');
  L.push('- **Fixed environment.** Runs use a fixed time zone and a restricted tool set; results may differ in an unrestricted session.');
  L.push('');
  return L.join('\n');
}

function esc(t) {
  return String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
function clip(t, max) { return t.length > max ? t.slice(0, max - 1) + '…' : t; }

function renderSvg(s) {
  const FONT = "-apple-system,'Segoe UI',Helvetica,Arial,sans-serif";
  const W = 1000;
  const rowH = 46;
  const n = s.tasks.length;
  const chartTop = 232;
  const H = chartTop + 34 + n * rowH + 52;
  const o = [];
  const text = (x, y, size, fill, str, extra) => o.push('<text x="' + x + '" y="' + y + '" font-family="' + FONT + '" font-size="' + size + '" fill="' + fill + '"' + (extra || '') + '>' + esc(str) + '</text>');

  o.push('<svg xmlns="http://www.w3.org/2000/svg" width="' + W + '" height="' + H + '" viewBox="0 0 ' + W + ' ' + H + '" role="img" aria-label="Token cost benchmark: median cost per task with lessons off versus on">');
  o.push('<title>Token cost benchmark: median cost per task with lessons off versus on</title>');
  o.push('<rect width="' + W + '" height="' + H + '" fill="#0f172a"/>');
  o.push('<rect x="12" y="12" width="' + (W - 24) + '" height="' + (H - 24) + '" rx="10" fill="#0b1220" stroke="#334155" stroke-width="1.5"/>');
  text(36, 52, 22, '#e2e8f0', 'Do lessons save tokens? A/B benchmark', ' font-weight="700"');
  text(36, 76, 13, '#94a3b8', 'Model ' + s.models.join(', ') + ' · ' + (s.off.n + s.on.n) + ' runs · ' + s.tasks.length + ' tasks · hooks disabled vs enabled');

  // Headline cards.
  const cards = [
    { label: 'TOTAL COST', off: usd(s.off.totalCost), on: usd(s.on.totalCost), d: delta(s.off.totalCost, s.on.totalCost) },
    { label: 'TASKS SOLVED', off: frac(s.off), on: frac(s.on), d: '' },
    { label: 'COST PER SOLVED TASK', off: usd(perSolved(s.off)), on: usd(perSolved(s.on)), d: delta(perSolved(s.off), perSolved(s.on)) },
  ];
  const cw = 296;
  const gap = 16;
  cards.forEach((c, i) => {
    const x = 36 + i * (cw + gap);
    o.push('<rect x="' + x + '" y="98" width="' + cw + '" height="108" rx="8" fill="#0f172a" stroke="#334155"/>');
    text(x + 16, 122, 11, '#94a3b8', c.label, ' letter-spacing="1.2" font-weight="600"');
    text(x + 16, 156, 22, '#94a3b8', 'off ' + c.off, ' font-weight="600"');
    text(x + 16, 186, 22, '#2dd4bf', 'on  ' + c.on, ' font-weight="700"');
    if (c.d) text(x + cw - 16, 186, 15, c.d.startsWith('-') ? '#2dd4bf' : '#fbbf24', c.d, ' text-anchor="end" font-weight="600"');
  });

  // Grouped bars.
  const labelX = 36;
  const barX = 250;
  const barMax = 560;
  const max = Math.max(1e-9, ...s.tasks.flatMap((t) => [t.off.medCost || 0, t.on.medCost || 0]));
  text(labelX, chartTop, 13, '#e2e8f0', 'Median cost per run, by task', ' font-weight="600"');
  o.push('<rect x="' + (barX) + '" y="' + (chartTop - 11) + '" width="12" height="12" rx="2" fill="#64748b"/>');
  text(barX + 18, chartTop, 12, '#94a3b8', 'off');
  o.push('<rect x="' + (barX + 64) + '" y="' + (chartTop - 11) + '" width="12" height="12" rx="2" fill="#2dd4bf"/>');
  text(barX + 82, chartTop, 12, '#94a3b8', 'on');
  s.tasks.forEach((t, i) => {
    const y = chartTop + 22 + i * rowH;
    text(labelX, y + 19, 13, '#e2e8f0', clip(t.task, 26));
    [['off', '#64748b', t.off], ['on', '#2dd4bf', t.on]].forEach(([name, color, c], j) => {
      const by = y + j * 19;
      const w = c.medCost == null ? 0 : Math.max(2, Math.round((c.medCost / max) * barMax));
      o.push('<rect x="' + barX + '" y="' + by + '" width="' + w + '" height="14" rx="3" fill="' + color + '"/>');
      text(barX + w + 8, by + 12, 11.5, name === 'on' ? '#2dd4bf' : '#94a3b8', usd(c.medCost) + ' · ' + frac(c) + ' solved');
    });
  });
  const fy = chartTop + 22 + n * rowH + 16;
  text(36, fy, 11.5, '#64748b', 'Median over repetitions; bars start at zero. Synthetic tasks, one model, small n: see RESULTS.md for limitations.');
  o.push('</svg>');
  return o.join('\n') + '\n';
}

function renderCompact(s) {
  const L = [];
  L.push('| Task | Solved off / on | Median cost off / on | Δ cost |');
  L.push('|---|---|---|---|');
  for (const t of s.tasks) {
    L.push('| ' + [t.task, frac(t.off) + ' / ' + frac(t.on), usd(t.off.medCost) + ' / ' + usd(t.on.medCost), delta(t.off.medCost, t.on.medCost)].join(' | ') + ' |');
  }
  L.push('| **Total** | ' + [frac(s.off) + ' / ' + frac(s.on), usd(s.off.totalCost) + ' / ' + usd(s.on.totalCost), delta(s.off.totalCost, s.on.totalCost)].join(' | ') + ' |');
  L.push('| **Cost per solved task** | | ' + usd(perSolved(s.off)) + ' / ' + usd(perSolved(s.on)) + ' | ' + delta(perSolved(s.off), perSolved(s.on)) + ' |');
  return L.join('\n');
}

function main() {
  let a;
  try { a = parseArgs(process.argv.slice(2)); } catch (e) { console.error(e.message); return 2; }
  const runs = readRuns(a.input);
  if (!runs.length) { console.error('no runs in ' + a.input); return 1; }
  const s = summarize(runs);
  fs.mkdirSync(path.dirname(a.md), { recursive: true });
  fs.mkdirSync(path.dirname(a.svg), { recursive: true });
  fs.writeFileSync(a.md, renderMarkdown(s, path.basename(a.input)));
  fs.writeFileSync(a.svg, renderSvg(s));
  console.log(renderCompact(s));
  return 0;
}

process.exitCode = main();
