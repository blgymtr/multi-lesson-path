'use strict';
// Read + normalize Claude Code transcript JSONL (streaming, tolerant).
const fs = require('fs');
const os = require('os');
const path = require('path');
const readline = require('readline');
const zlib = require('zlib');

const MAX_LINE = 5 * 1024 * 1024;
const MAX_TEXT = 2000;
const WANTED_RE = /"type":\s*"(user|assistant|custom-title|summary)"/;
const KEEP_INPUT_KEYS = ['command', 'file_path', 'notebook_path', 'path', 'pattern', 'description', 'url', 'query', 'old_string', 'new_string', 'content', 'prompt', 'subagent_type'];

function trunc(s, n) {
  s = typeof s === 'string' ? s : s == null ? '' : String(s);
  n = n || MAX_TEXT;
  return s.length > n ? s.slice(0, n) + '…' : s;
}

function expandHome(p) {
  if (typeof p !== 'string') return p;
  if (p === '~') return os.homedir();
  if (p.startsWith('~/') || p.startsWith('~\\')) return path.join(os.homedir(), p.slice(2));
  return p;
}

const INJECTED_TAGS = [
  'system-reminder', 'command-name', 'command-message', 'command-args', 'command-contents',
  'local-command-stdout', 'local-command-stderr', 'local-command-caveat', 'task-notification',
  'user-prompt-submit-hook', 'bash-input', 'bash-stdout', 'bash-stderr', 'ide_opened_file',
  'ide_selection', 'session-start-hook', 'hook-stdout'
];
const TAG_RES = INJECTED_TAGS.map((t) => new RegExp('<' + t + '(?:\\s[^>]*)?>[\\s\\S]*?</' + t + '>', 'gi'));
const DANGLING_RES = INJECTED_TAGS.map((t) => new RegExp('<' + t + '(?:\\s[^>]*)?>[\\s\\S]*$', 'i'));

/** Strip injected system/hook content from a user message. Returns '' if nothing real remains. */
function cleanUserText(text) {
  if (typeof text !== 'string') return '';
  let t = text;
  for (const re of TAG_RES) t = t.replace(re, ' ');
  for (const re of DANGLING_RES) t = t.replace(re, ' ');
  t = t.trim();
  if (/^\[Request interrupted by user/i.test(t)) return '';
  if (/^Caveat: The messages below were generated by the user while running local commands/i.test(t)) return '';
  return t;
}

function blockText(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  const out = [];
  for (const b of content) {
    if (!b) continue;
    if (typeof b === 'string') out.push(b);
    else if (b.type === 'text' && typeof b.text === 'string') out.push(b.text);
    else if (b.type === 'image') out.push('[image]');
  }
  return out.join('\n');
}

function slimInput(input) {
  if (!input || typeof input !== 'object') return {};
  const out = {};
  for (const k of KEEP_INPUT_KEYS) {
    if (input[k] != null) out[k] = trunc(typeof input[k] === 'string' ? input[k] : JSON.stringify(input[k]), MAX_TEXT);
  }
  return out;
}

function slugFromFile(file) {
  const parts = path.resolve(file).split(path.sep);
  const i = parts.length;
  // <slug>/<sid>/subagents/x.jsonl
  if (parts[i - 2] === 'subagents' && i >= 4) return parts[i - 4];
  return parts[i - 2] || 'unknown';
}

/**
 * Consume an async iterable of lines (raw Claude Code JSONL or our condensed archive format).
 */
async function parseLines(lines, opts) {
  opts = opts || {};
  const res = { sessionId: opts.sessionId || null, title: null, summary: null, cwd: null, project: null, slug: opts.slug || null, start: null, end: null, events: [] };
  const toolUses = new Map();
  let n = 0;
  let seenSid = false;
  const touch = (ts) => {
    if (!ts) return;
    if (!res.start || ts < res.start) res.start = ts;
    if (!res.end || ts > res.end) res.end = ts;
  };
  for await (const line of lines) {
    n++;
    if (!line || line.length > MAX_LINE) continue;
    if (line.charCodeAt(0) !== 123) continue;
    // Cheap pre-filter: find the "type" within the head, skip uninteresting types without parsing.
    const head = line.length > 3000 ? line.slice(0, 3000) : line;
    if (!WANTED_RE.test(head) && !head.includes('"meta"') && !head.includes('"kind"')) continue;
    let o = null;
    try { o = JSON.parse(line); } catch (e) { continue; }
    if (!o || typeof o !== 'object') continue;

    if (o.meta && typeof o.meta === 'object') { // condensed archive header
      const mt = o.meta;
      res.sessionId = mt.sessionId || res.sessionId; seenSid = true;
      res.title = mt.title || res.title;
      res.summary = mt.summary || res.summary;
      res.cwd = mt.cwd || res.cwd;
      res.project = mt.project || res.project;
      res.slug = mt.slug || res.slug;
      res.start = mt.start || res.start;
      res.end = mt.end || res.end;
      continue;
    }
    if (o.kind && typeof o.kind === 'string' && !o.type) { // condensed event
      res.events.push(o);
      if (o.id && o.kind === 'tool_use') toolUses.set(o.id, o);
      continue;
    }
    if (o.sessionId && !seenSid) { res.sessionId = o.sessionId; seenSid = true; }
    if (o.cwd && !res.cwd) res.cwd = o.cwd;
    if (o.type === 'custom-title') {
      const t = o.customTitle || o.title;
      if (typeof t === 'string' && t) res.title = t;
      continue;
    }
    if (o.type === 'summary') {
      if (typeof o.summary === 'string' && o.summary) res.summary = o.summary;
      continue;
    }
    if (o.isSidechain === true && !opts.includeSidechain) continue;
    if (o.isMeta === true) continue;
    const ts = o.timestamp || null;
    const msg = o.message;
    if (!msg || typeof msg !== 'object') continue;
    const uid = o.uuid || 'L' + n;

    if (o.type === 'user') {
      touch(ts);
      const c = msg.content;
      if (typeof c === 'string') {
        const t = cleanUserText(c);
        if (t) res.events.push({ ts, kind: 'user', text: trunc(t, opts.userChars || 4000), id: uid });
      } else if (Array.isArray(c)) {
        const texts = [];
        for (let bi = 0; bi < c.length; bi++) {
          const b = c[bi];
          if (!b) continue;
          if (b.type === 'tool_result') {
            const tu = toolUses.get(b.tool_use_id);
            res.events.push({
              ts, kind: 'tool_result', id: b.tool_use_id || uid + ':' + bi,
              tool: tu ? tu.tool : undefined, input: tu ? tu.input : undefined,
              isError: b.is_error === true, text: trunc(blockText(b.content), MAX_TEXT)
            });
          } else if (b.type === 'text') {
            texts.push(b.text || '');
          }
        }
        const t = cleanUserText(texts.join('\n'));
        if (t) res.events.push({ ts, kind: 'user', text: trunc(t, opts.userChars || 4000), id: uid });
      }
    } else if (o.type === 'assistant') {
      touch(ts);
      const c = msg.content;
      if (typeof c === 'string') {
        if (c.trim()) res.events.push({ ts, kind: 'assistant', text: trunc(c, opts.assistantChars || 4000), id: uid });
      } else if (Array.isArray(c)) {
        const texts = [];
        for (const b of c) {
          if (!b) continue;
          if (b.type === 'text' && b.text) texts.push(b.text);
          else if (b.type === 'tool_use') {
            if (texts.length) { res.events.push({ ts, kind: 'assistant', text: trunc(texts.join('\n'), opts.assistantChars || 4000), id: uid }); texts.length = 0; }
            const ev = { ts, kind: 'tool_use', tool: b.name, input: slimInput(b.input), id: b.id || uid };
            res.events.push(ev);
            if (b.id) toolUses.set(b.id, ev);
          }
        }
        if (texts.length) res.events.push({ ts, kind: 'assistant', text: trunc(texts.join('\n'), opts.assistantChars || 4000), id: uid });
      }
    }
  }
  if (!res.project && res.cwd) res.project = String(res.cwd).split(/[\\/]/).filter(Boolean).pop() || null;
  return res;
}

function lineIterator(stream) {
  return readline.createInterface({ input: stream, crlfDelay: Infinity });
}

/** Read a raw Claude Code transcript file. */
async function readTranscript(file, opts) {
  opts = Object.assign({}, opts);
  const stream = fs.createReadStream(file, { encoding: 'utf8' });
  const rl = lineIterator(stream);
  try {
    return await parseLines(rl, Object.assign({ slug: slugFromFile(file), sessionId: path.basename(file, '.jsonl') }, opts));
  } finally {
    rl.close();
    stream.destroy();
  }
}

/** Read a .jsonl.gz written by lib/archive.js (condensed or full). */
async function readArchived(gzFile, opts) {
  const src = fs.createReadStream(gzFile);
  const gunzip = zlib.createGunzip();
  gunzip.setEncoding('utf8');
  src.pipe(gunzip);
  src.on('error', (e) => gunzip.destroy(e));
  const rl = lineIterator(gunzip);
  try {
    return await parseLines(rl, opts);
  } finally {
    rl.close();
    src.destroy();
  }
}

/** All top-level transcripts (not sub-agents) under the given roots. */
function listTranscripts(roots) {
  const out = [];
  for (const r of roots || []) {
    const root = expandHome(r);
    let slugs;
    try { slugs = fs.readdirSync(root, { withFileTypes: true }); } catch (e) { continue; }
    for (const d of slugs) {
      if (!d.isDirectory()) continue;
      const dir = path.join(root, d.name);
      let files;
      try { files = fs.readdirSync(dir, { withFileTypes: true }); } catch (e) { continue; }
      for (const f of files) {
        if (!f.isFile() || !f.name.endsWith('.jsonl')) continue;
        const full = path.join(dir, f.name);
        try {
          const st = fs.statSync(full);
          out.push({ file: full, slug: d.name, sessionId: f.name.slice(0, -6), size: st.size, mtimeMs: st.mtimeMs });
        } catch (e) { /* vanished */ }
      }
    }
  }
  return out;
}

module.exports = { readTranscript, readArchived, parseLines, listTranscripts, cleanUserText, slugFromFile, expandHome, trunc, MAX_LINE, MAX_TEXT };
